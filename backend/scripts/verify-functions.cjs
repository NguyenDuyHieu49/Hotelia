/* Starts the built API against an isolated temporary database; never touches the app database. */
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {randomUUID,createHash}=require('node:crypto');
const {spawn}=require('node:child_process');
const mongoose=require('mongoose');
const bcrypt=require('bcrypt');
const jwt=require('jsonwebtoken');
const dotenv=require('dotenv');
const root=path.resolve(__dirname,'..');
const env=dotenv.parse(fs.readFileSync(path.join(root,'.env')));
const database='hotelia_functions_test_'+randomUUID().replaceAll('-','').slice(0,10);
const uri=new URL(process.env.MONGODB_URI || env.MONGODB_URI);
uri.pathname='/'+database;
const secret=randomUUID()+randomUUID();
const port=String(32000+Math.floor(Math.random()*2000));
const base=`http://127.0.0.1:${port}/api/v1`;
let server;
const wait=ms=>new Promise(r=>setTimeout(r,ms));
let checks=0;
async function call(route,token,method='GET',body,status=200) {
  const response=await fetch(base+route,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined,signal:AbortSignal.timeout(15000)});
  const data=await response.json();
  assert.equal(response.status,status,`${method} ${route} returned ${response.status}: ${JSON.stringify(data.error?.message || data.message || '')}`);
  checks++;return data;
}
async function run() {
  await mongoose.connect(uri.toString());
  const db=mongoose.connection.db;
  assert.equal(db.databaseName,database);
  const actors={};
  const password='TestOnlyPassword123!';
  const passwordHash=await bcrypt.hash(password,12);
  for(const [name,role] of [['owner','OWNER'],['guest','USER'],['other','USER'],['admin','ADMIN']]) {
    const _id=new mongoose.Types.ObjectId();
    const email=`${name}@functions.test`;
    await db.collection('users').insertOne({_id,email,name,role,isActive:true,passwordHash,tokenVersion:0});
    actors[name]={id:_id,email,token:jwt.sign({sub:String(_id),email,role,tokenVersion:0},secret,{expiresIn:'1h'})};
  }
  server=spawn(process.execPath,['dist/main.js'],{cwd:root,env:{...process.env,...env,MONGODB_URI:uri.toString(),JWT_SECRET:secret,PORT:port,RESET_EMAIL_WEBHOOK_URL:'',RESET_EMAIL_WEBHOOK_TOKEN:''},stdio:'ignore'});
  let ready=false;
  for(let i=0;i<60;i++) {try {ready=(await fetch(`http://127.0.0.1:${port}/health`)).ok;} catch {} if(ready)break;if(server.exitCode!==null)throw new Error('Test API failed to start');await wait(500);}
  assert(ready,'Test API did not start');
  const owner=actors.owner.token,guest=actors.guest.token,other=actors.other.token,admin=actors.admin.token;
  const h=await call('/hotels',owner,'POST',{name:'Regression Hotel',description:'Private temporary regression fixture',address:'Test address',city:'Hà Nội',starRating:4},201);
  assert.equal(h.status,'DRAFT');
  const room=await call(`/room-types/hotel/${h._id}`,owner,'POST',{name:'Fixture Room',description:'Temporary test room',basePrice:735000,maxGuests:2,totalRooms:1},201);
  await call(`/hotels/${h._id}/submit`,owner,'POST',{},201);
  await call(`/admin/hotels/${h._id}/approve`,guest,'POST',{},403);
  await call(`/admin/hotels/${h._id}/approve`,admin,'POST',{},201);
  const today=new Date(Date.now()+7*3600000).toISOString().slice(0,10);
  const checkout=new Date(+new Date(today)+2*86400000).toISOString().slice(0,10);
  const bookingBody={hotelId:h._id,roomTypeId:room._id,checkIn:today,checkOut:checkout,guestCount:2,guestName:'Fixture Guest',guestEmail:actors.guest.email,guestPhone:'0900000000'};
  const roomsForStay=()=>call(`/room-types/hotel/${h._id}?checkIn=${today}&checkOut=${checkout}`,guest);
  assert.equal((await roomsForStay())[0].availableRooms,1);
  await call(`/room-types/hotel/${h._id}?checkIn=${today}`,guest,'GET',undefined,400);
  await call('/bookings',guest,'POST',{...bookingBody,guestCount:3},400);
  await call('/bookings',guest,'POST',{...bookingBody,roomTypeId:String(new mongoose.Types.ObjectId())},400);
  const attempts=await Promise.all([guest,other,guest].map(token=>fetch(base+'/bookings',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+token},body:JSON.stringify(bookingBody)}).then(async r=>({status:r.status,data:await r.json(),token}))));
  assert.equal(attempts.filter(a=>a.status===201).length,1,'Concurrent reservations oversold the room');
  assert.equal(attempts.filter(a=>a.status===400).length,2);
  const winner=attempts.find(a=>a.status===201),b=winner.data,booker=winner.token;
  const notBooker=booker===guest?other:guest;
  assert.equal(b.roomPrice,735000);assert.equal(b.totalPrice,1470000);assert.equal(b.nights,2);
  await call(`/bookings/${b._id}`,notBooker,'GET',undefined,403);
  const query=`?sessionId=${randomUUID()}&checkIn=${today}&checkOut=${checkout}&guests=2`;
  assert.equal((await call('/recommendations'+query,guest)).hotels.length,0);
  assert.equal((await call(`/room-types/${room._id}/availability?start=${today}&end=${today}`,guest))[0].availableRooms,0);
  assert.equal((await roomsForStay())[0].availableRooms,0);
  await call(`/bookings/${b._id}/cancel`,booker,'POST',{},201);
  assert.equal((await roomsForStay())[0].availableRooms,1);
  assert.equal((await call('/recommendations'+query,guest)).hotels.length,1);
  assert.equal((await call('/recommendations'+query+'&maxPrice=700000',guest)).hotels.length,0);
  assert.equal((await call('/recommendations'+query+'&minRating=4',guest)).hotels.length,0);
  const next=await call('/bookings',guest,'POST',bookingBody,201);
  assert.equal((await call(`/bookings/${next._id}/pay-at-hotel`,guest,'POST',{},201)).status,'CONFIRMED');
  assert.equal((await call(`/bookings/${next._id}/pay-at-hotel`,guest,'POST',{},201)).status,'CONFIRMED');
  await call(`/bookings/${next._id}/check-in`,other,'POST',{},403);
  await call(`/bookings/${next._id}/check-in`,owner,'POST',{},201);
  await call(`/bookings/${next._id}/check-out`,owner,'POST',{},201);
  await call('/reviews',other,'POST',{hotelId:h._id,rating:5,content:'Not a guest of this property'},403);
  const review=await call('/reviews',guest,'POST',{hotelId:h._id,bookingId:next._id,rating:5,content:'An actual completed fixture stay'},201);
  await call('/reviews',guest,'POST',{hotelId:h._id,bookingId:next._id,rating:4,content:'Duplicate review should fail'},403);
  assert.equal((await call(`/hotels/${h._id}`,guest)).reviewCount,1);
  await call(`/reviews/${review._id}/reply`,owner,'POST',{reply:'Thank you for your review'},201);
  assert.equal((await call('/reviews/owner',owner)).length,1);
  await call(`/reviews/${review._id}/hide`,admin,'POST',{},201);
  assert.equal((await call(`/hotels/${h._id}`,guest)).reviewCount,0);
  await db.collection('reviews').updateOne({_id:new mongoose.Types.ObjectId(review._id)},{$set:{isVisible:true}});
  const publicReviews=await call(`/reviews/hotel/${h._id}`,guest);
  assert.equal(typeof publicReviews.reviews[0].userId,'string');
  await call(`/reviews/${review._id}/helpful`,null,'POST',{},401);
  await call(`/reviews/${review._id}/helpful`,guest,'POST',{},403);
  assert.equal((await call(`/reviews/${review._id}/helpful`,other,'POST',{},201)).helpfulCount,1);
  assert.equal((await call(`/reviews/${review._id}/helpful`,other,'POST',{},201)).helpfulCount,1);
  assert.equal((await call(`/reviews/${review._id}/helpful`,admin,'POST',{},201)).helpfulCount,2);
  await call(`/account/favorites/${h._id}`,guest,'PUT',{});
  await call(`/account/favorites/${h._id}`,guest,'PUT',{});
  assert.equal((await call('/account/favorites',guest)).length,1);
  assert.equal((await call('/account/favorites',other)).length,0);
  await call(`/account/favorites/${h._id}`,guest,'DELETE');
  assert.equal((await call('/account/favorites',guest)).length,0);
  const ticket=await call('/account/support',guest,'POST',{subject:'Booking question',message:'Please check this private fixture request'},201);
  assert.equal((await call('/account/support',other)).length,0);
  await call(`/account/support/${ticket._id}/reply`,admin,'POST',{reply:'Fixture resolved'},201);
  assert.equal((await call('/account/support',guest))[0].status,'RESOLVED');
  const notifications=await call('/notifications',guest);
  assert(notifications.notifications.length>0);
  await call('/notifications/read-all',guest,'POST',{},201);
  assert.equal((await call('/notifications',guest)).unread,0);
  const flexibleRoom=await call(`/room-types/hotel/${h._id}`,owner,'POST',{name:'Flexible Room',description:'Inventory regression fixture',basePrice:990000,maxGuests:2,totalRooms:2},201);
  const flexibleBody={...bookingBody,roomTypeId:flexibleRoom._id};
  const firstFlexible=await call('/bookings',guest,'POST',flexibleBody,201);
  await call('/bookings',other,'POST',flexibleBody,201);
  await call(`/room-types/${flexibleRoom._id}`,owner,'PUT',{totalRooms:1},400);
  await call(`/bookings/${firstFlexible._id}/cancel`,guest,'POST',{},201);
  assert.equal((await call(`/room-types/${flexibleRoom._id}`,owner,'PUT',{totalRooms:1})).totalRooms,1);
  const cheapHotel=await call('/hotels',owner,'POST',{name:'Budget Fixture',description:'Temporary budget fixture',address:'Test address',city:'Hà Nội',starRating:3,amenities:['wifi']},201);
  await call(`/room-types/hotel/${cheapHotel._id}`,owner,'POST',{name:'Budget Room',description:'Temporary budget room',basePrice:350000,maxGuests:2,totalRooms:1},201);
  await call(`/hotels/${cheapHotel._id}/submit`,owner,'POST',{},201);
  await call(`/admin/hotels/${cheapHotel._id}/approve`,admin,'POST',{},201);
  assert.equal((await call('/hotels?sortBy=price_low')).hotels[0]._id,cheapHotel._id);
  assert.equal((await call('/hotels?sortBy=price_high')).hotels[0]._id,h._id);
  assert.equal((await call('/hotels?amenities=wifi')).hotels.length,1);
  assert.equal((await call('/hotels?destination=%5B')).hotels.length,0);
  assert((await call('/owners/bookings',owner)).length>=2);
  await call('/owners/bookings',guest,'GET',undefined,403);
  await call('/admin/bookings',guest,'GET',undefined,403);
  const users=await call('/admin/users',admin);
  assert(users.users.every(u=>!u.passwordHash && !u.refreshToken));
  await call('/payments',guest,'POST',{bookingId:next._id,method:'MOMO',returnUrl:'https://example.test/return'},503);
  await call('/payments/callback/momo',null,'POST',{transactionId:'fake'},503);
  await call('/auth/forgot-password',null,'POST',{email:actors.guest.email},503);
  assert((await call('/admin/audit-logs',admin)).length>0);
  await call('/admin/audit-logs',guest,'GET',undefined,403);
  await call('/owners/apply',other,'POST',{businessName:'Fixture Partner'},201);
  const pending=await call('/admin/owners/pending',admin);
  assert(pending.some(u=>String(u.id)===String(actors.other.id)));
  await call(`/admin/owners/${actors.other.id}/reject`,admin,'POST',{},201);
  await call('/account/password',guest,'POST',{currentPassword:'wrong',newPassword:'UpdatedPassword123!'},400);
  await call('/account/password',guest,'POST',{currentPassword:password,newPassword:'UpdatedPassword123!'},201);
  await call('/account/favorites',guest,'GET',undefined,401);
  await call('/auth/login',null,'POST',{email:actors.guest.email,password},401);
  await call('/auth/login',null,'POST',{email:actors.guest.email,password:'UpdatedPassword123!'});
  const code='fixture-one-time-code-'+randomUUID();
  await db.collection('password_resets').insertOne({userId:actors.guest.id,tokenHash:createHash('sha256').update(code).digest('hex'),expiresAt:new Date(Date.now()+60000)});
  await call('/auth/reset-password',null,'POST',{code,password:'RecoveredPassword123!'},201);
  await call('/auth/reset-password',null,'POST',{code,password:'AnotherPassword123!'},400);
  await call('/auth/login',null,'POST',{email:actors.guest.email,password:'RecoveredPassword123!'});
  console.log(JSON.stringify({status:'PASS',apiChecks:checks,concurrentBookingAttempts:3,overselling:false,isolatedDatabase:true,realAppDataChanged:false},null,2));
}
run().catch(e=>{console.error(e.message);process.exitCode=1;}).finally(async()=>{
  if(server) {server.kill('SIGTERM');await wait(500);}
  if(mongoose.connection.db?.databaseName===database && database.startsWith('hotelia_functions_test_')) {
    await mongoose.connection.db.dropDatabase();console.log('Removed temporary regression database.');
  }
  await mongoose.disconnect();
});
